const dicts: Record<UiLang, Dict> = { en, fi, sv };

/** Fixed UI text. `{name}` placeholders are filled from `vars`. */
export function t(key: UiKey, lang: UiLang, vars?: Record<string, string | number>): string {
  const text = dicts[lang][key] ?? en[key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

const DIET_KEYS: Partial<Record<string, UiKey>> = {
  gluten_free: 'diet.gluten_free',
  lactose_free: 'diet.lactose_free',
  vegan: 'diet.vegan',
  vegetarian: 'diet.vegetarian',
  nuts: 'diet.nuts',
};

/** "gluten-free", or a generic "special diet" for anything without a translation. */
export function dietLabel(diet: string, lang: UiLang): string {
  return t(DIET_KEYS[diet] ?? 'diet.other', lang);
}

export function uiLangFor(lang?: Lang): UiLang {
  const base = lang?.toLowerCase().split(/[-_]/)[0];
  return base === 'fi' || base === 'sv' ? base : 'en';
}

/** BCP-47 locale for Intl formatting of numbers, money and dates. */
export function localeFor(lang: UiLang): string {
  return lang === 'fi' ? 'fi-FI' : lang === 'sv' ? 'sv-FI' : 'en-GB';
}
